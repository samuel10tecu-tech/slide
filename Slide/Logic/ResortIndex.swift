    static func match(latitude: Double, longitude: Double) -> Resort? {
        var inside: [(Resort, Double)] = []
        var nearest: (Resort, Double)?
        for place in places {
            let meters = Geo.haversineMeters(lat1: latitude, lon1: longitude, lat2: place.latitude, lon2: place.longitude)
            let km = meters / 1000
            if km <= place.radiusKm { inside.append((place, km)) }
            if nearest == nil || km < nearest!.1 { nearest = (place, km) }
        }
        if let best = inside.min(by: { lhs, rhs in
            if lhs.0.radiusKm != rhs.0.radiusKm { return lhs.0.radiusKm < rhs.0.radiusKm }
            return lhs.1 < rhs.1
        }) {
            return best.0
        }
        if let nearest, nearest.1 <= 12 { return nearest.0 }
        return nil
    }

    static func match(samples: [TrackSample]) -> Resort? {
        guard !samples.isEmpty else { return nil }
        let latitude = samples.reduce(0.0) { $0 + $1.latitude } / Double(samples.count)
        let longitude = samples.reduce(0.0) { $0 + $1.longitude } / Double(samples.count)
        return match(latitude: latitude, longitude: longitude)
    }
