#!/usr/bin/env python3
"""Write the Android string resources from the iOS String Catalog.

Every key of Slide/Localization/Localizable.xcstrings becomes a resource named like the key with dots and dashes
turned into underscores (tracking.stat.max -> tracking_stat_max), in all 14 languages. Android-only texts come from
tooling/i18n/android_only.py. Run it after tooling/build_catalog.py; the output is committed.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tooling" / "i18n"))
from android_only import ANDROID, LANGS  # noqa: E402

CATALOG = ROOT / "Slide" / "Localization" / "Localizable.xcstrings"
RES = ROOT / "android" / "app" / "src" / "main" / "res"
FOLDER = {"en": "values", "zh-Hans": "values-b+zh+Hans"}


def resource_name(key: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", key)


def android_value(text: str) -> str:
    text = text.replace("%@", "%s").replace("%lld", "%d").replace("%ld", "%d")
    text = text.replace("\\", "\\\\")
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text[:1] in ("@", "?"):
        text = "\\" + text
    return text


def main() -> None:
    strings = json.loads(CATALOG.read_text())["strings"]
    rows: dict[str, dict[str, str]] = {}
    for key, entry in strings.items():
        local = entry.get("localizations", {})
        english = local["en"]["stringUnit"]["value"]
        rows[key] = {lang: local.get(lang, {}).get("stringUnit", {}).get("value", english) for lang in LANGS}
    for key, values in ANDROID.items():
        if len(values) != len(LANGS):
            raise SystemExit(f"{key}: expected {len(LANGS)} translations, got {len(values)}")
        rows[key] = dict(zip(LANGS, values))

    names: dict[str, str] = {}
    for key in rows:
        name = resource_name(key)
        if name in names:
            raise SystemExit(f"resource name clash: {key} and {names[name]}")
        names[name] = key

    for lang in LANGS:
        folder = RES / FOLDER.get(lang, f"values-{lang}")
        folder.mkdir(parents=True, exist_ok=True)
        lines = [
            '<?xml version="1.0" encoding="utf-8"?>',
            "<!-- Generated by tooling/android_strings.py from Localizable.xcstrings. Do not edit by hand. -->",
            '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation,UnusedResources,Typos">',
        ]
        for key in sorted(rows):
            value = android_value(rows[key][lang])
            formatted = ' formatted="false"' if "%" in value else ""
            lines.append(f'    <string name="{resource_name(key)}"{formatted}>{value}</string>')
        lines.append("</resources>")
        (folder / "strings_slide.xml").write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} strings x {len(LANGS)} languages")


if __name__ == "__main__":
    main()
