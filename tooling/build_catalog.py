def trick(tid, name_en, name_fr, summary_en, summary_fr, steps, safety_en, safety_fr, tips):
    add(f"trick.{tid}.name", name_en, name_fr)
    add(f"trick.{tid}.summary", summary_en, summary_fr)
    add(f"trick.{tid}.safety", safety_en, safety_fr)
    for i, (en, fr) in enumerate(steps):
        add(f"trick.{tid}.step.{i}", en, fr)
    for i, (en, fr) in enumerate(tips):
        add(f"trick.{tid}.tip.{i}", en, fr)

